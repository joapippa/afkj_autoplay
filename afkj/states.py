"""
画面状態の定義
==============
「この画面ではこのテンプレートが見える」という対応表。

旧版は Step1→2→3→4 の固定手順で、1つでも見つからないと停止していた。
ここでは画面ごとに独立した状態として定義し、実行時は「今どの画面か」を
毎回判定して動く。おかげでクリックが空振りしても、次の周回で同じ画面が
見えるので自然に押し直しになる。

★ ゲームの更新で UI が変わったら、まずここを見直すこと。
   テンプレート名は templates.json のキーと一致させる。


周回の流れ
----------
    ステージ選択 ─[幻霊挑戦/挑戦]→ 編成画面
    編成画面 ─[クリア編成]→ 編成ポップアップ ─[一括適用]→[タップで閉じる]→ 編成画面
    編成画面 ─[戦闘]→ 戦闘（1戦だけ）─[Skip]→ すぐに勝敗の画面
    戦闘 ─勝ち→ 戦闘勝利 ─[← 戻る]→ ステージ選択 → 次のステージのクリア編成を当て直す
    戦闘 ─負け→ 戦闘敗北 ─[もう一度]→ 編成画面 へ戻る
    諦めるとき: 戦闘敗北／編成画面 ─[← 戻る]→ ステージ選択

「オート挑戦」は押さない。オート挑戦は勝つとその編成のまま次のステージへ
進むが、引き継いだ編成の次ステージ勝率は 27/82 = 33% しかなく、その
ステージのクリア履歴1番目（50/64 = 78%）に大きく劣った（2026-10-05 の実行）。
1戦ずつ戦えば、ステージごとにクリア履歴の編成を当て直せる。

戦闘勝利から ← で戻る流れは 2026-10-05 の実走（115勝）で確かめた。

結社戦線（Union Campaign）の流れ
--------------------------------
編成画面から先は先鋒ステージと同じ画面・同じボタンなので、同じ状態を使う
（テンプレートも先鋒のものがそのまま 0.87〜0.99 で当たった）。違うのは入口まで。

    ワールド画面 ─[モード]→ モード画面 ─[ギルド]→ ギルドのモード画面
    ギルドのモード画面 ─[結社戦線]→ 結社戦線の画面 ─[挑戦]→ 編成画面
    （地図画面が開いていたら ← でワールド画面へ戻る）
    戦闘勝利 ─[← 戻る]→ 結社戦線の画面 → 次のフロアのクリア編成を当て直す

ステージは「フロア」と呼ばれ、結社戦線の画面に「現在：22」と出ている。
1フロアは3つの WAVE からなる（画面上部の ◇>>◇>>◇）。

勝利画面は先鋒と同じ「戦闘勝利」の見出しで、下に ← / 統計 / 続ける が並ぶ。
← で結社戦線の画面へ戻る流れは 2026-10-12 の実走（4フロア）で確かめた。

どちらを回すかで有効な状態を切り替える（StateSpec.content）。
結社戦線の「挑戦」と先鋒ステージ選択の「挑戦」は白黒では見分けられず
（先鋒の 挑戦_btn が結社戦線の画面に 0.86 で当たる）、両方を同時に有効に
すると別のコンテンツに入ってしまうため。

編成ポップアップには右端に「>」ボタンがあり、押すごとに2番目・3番目…の
クリア編成が表示される。表示中の編成が一括適用の対象になる。

編成画面のボタン列は左から ← / クリア編成 / オート挑戦 / 戦闘。
押すのは「戦闘」（1戦だけ戦う）。「オート挑戦」は押さない。

「オート挑戦中」の表示はオート挑戦のときにしか出ないので、1戦ずつ戦う
ときは戦闘画面の一時停止ボタンと歯車ボタンで戦闘中を見分ける。

2026-10 の更新で戦闘画面の右下に「Skip」ボタンが増えた（並びは
x4 / x2 / 歯車 / Skip）。押すとすぐに勝敗の画面が出る。負けたときの画面は
最後まで戦ったときと同じ「戦闘敗北」（ユーザーが確認）。

「もう一度」で編成画面に戻ると、直前に当てた編成がそのまま残っている
（ユーザーが確認。記録画面でも英雄5人にチェックが付いたままだった）。
同じ編成で挑み直すときはクリア編成を開き直さずに「戦闘」を押す。
"""

