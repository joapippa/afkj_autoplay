# ★ クリアしたステージ数の数え方について
#   以前は戦闘画面の上部にある「幻霊先鋒ステージ N」の看板が変わった回数で
#   数えていたが、**今の版の戦闘画面には看板が出ていない**。あの位置に
#   写っていたのは背景の街並みで、カメラが動くだけで数字が増えていた
#   （実測: 0クリアの周回で3回計上、88クリアの周回で154回計上）。
#   今は戦闘勝利の画面に出ている数字をそのまま読む → digits.py
#   （オート挑戦を使っていたころは、オート戦闘終了の集計画面から読んでいた）


def required_templates() -> set[str]:
    """状態判定に使う全テンプレート名。"""
    return {name for state in STATES for name in state.detect}


def states_for(content: str) -> list[StateSpec]:
    """そのコンテンツを回すときに使う状態（共通のものを含む）。"""
    return [s for s in STATES if s.content in (None, content)]


